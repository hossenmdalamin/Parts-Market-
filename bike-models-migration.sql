-- Parts Market: dedicated Bike Models manager
create table if not exists public.bike_models (
  id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamptz not null default now()
);
create unique index if not exists bike_models_name_ci_unique
  on public.bike_models (lower(trim(name)));
alter table public.bike_models enable row level security;
drop policy if exists "Public can read bike models" on public.bike_models;
create policy "Public can read bike models" on public.bike_models
  for select to anon, authenticated using (true);
drop policy if exists "Admins manage bike models" on public.bike_models;
create policy "Admins manage bike models" on public.bike_models
  for all to authenticated using (public.is_admin()) with check (public.is_admin());
grant select on public.bike_models to anon, authenticated;
grant insert, update, delete on public.bike_models to authenticated;
-- Seed current compatibility names; case-insensitive duplicates are collapsed.
insert into public.bike_models (name)
select min(trim(token))
from public.products p
cross join lateral regexp_split_to_table(coalesce(p.compatibility, ''), '[,/|;]+') as token
where trim(token) <> ''
group by lower(trim(token))
on conflict do nothing;
