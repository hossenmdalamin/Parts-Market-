-- PARTS MARKET database setup (run in Supabase SQL Editor)
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'customer' check (role in ('customer','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  price numeric(12,2) not null check (price >= 0),
  category text not null default 'Other',
  stock integer not null default 0 check (stock >= 0),
  compatibility text default '',
  description text default '',
  image_url text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  phone text not null,
  address text not null,
  note text default '',
  total numeric(12,2) not null default 0,
  status text not null default 'pending' check (status in ('pending','confirmed','shipped','delivered','cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  unit_price numeric(12,2) not null,
  quantity integer not null check (quantity > 0)
);

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles where id = auth.uid() and role = 'admin'); $$;

drop policy if exists "public can read active products" on public.products;
create policy "public can read active products" on public.products for select using (active = true or public.is_admin());
drop policy if exists "admins manage products" on public.products;
create policy "admins manage products" on public.products for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists "users read own profile" on public.profiles;
create policy "users read own profile" on public.profiles for select using (id = auth.uid() or public.is_admin());
drop policy if exists "admins read all orders" on public.orders;
create policy "admins read all orders" on public.orders for select using (public.is_admin());
drop policy if exists "admins update orders" on public.orders;
create policy "admins update orders" on public.orders for update using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admins read order items" on public.order_items;
create policy "admins read order items" on public.order_items for select using (public.is_admin());

-- Customers submit orders through this validated RPC; no direct public table insert.
create or replace function public.place_order(
  p_customer_name text, p_phone text, p_address text, p_note text, p_items jsonb
) returns bigint
language plpgsql security definer set search_path = public
as $$
declare
  new_order_id bigint;
  item jsonb;
  prod public.products%rowtype;
  qty integer;
  order_total numeric(12,2) := 0;
begin
  if length(trim(coalesce(p_customer_name,''))) < 2
     or length(trim(coalesce(p_phone,''))) < 8
     or length(trim(coalesce(p_address,''))) < 8
     or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 then
    raise exception 'Please provide valid customer and order details';
  end if;

  -- Lock products and validate all requested quantities first.
  for item in select value from jsonb_array_elements(p_items)
  loop
    qty := (item->>'quantity')::integer;
    if qty < 1 then raise exception 'Invalid quantity'; end if;
    select * into prod from public.products
      where id = (item->>'product_id')::uuid and active = true
      for update;
    if not found then raise exception 'A selected product is unavailable'; end if;
    if prod.stock < qty then raise exception 'Insufficient stock for %', prod.name; end if;
    order_total := order_total + prod.price * qty;
  end loop;

  insert into public.orders(customer_name,phone,address,note,total)
  values(trim(p_customer_name),trim(p_phone),trim(p_address),coalesce(p_note,''),order_total)
  returning id into new_order_id;

  for item in select value from jsonb_array_elements(p_items)
  loop
    qty := (item->>'quantity')::integer;
    select * into prod from public.products where id = (item->>'product_id')::uuid for update;
    insert into public.order_items(order_id,product_id,product_name,unit_price,quantity)
    values(new_order_id,prod.id,prod.name,prod.price,qty);
    update public.products set stock = stock - qty where id = prod.id;
  end loop;
  return new_order_id;
end; $$;

revoke all on function public.place_order(text,text,text,text,jsonb) from public;
grant execute on function public.place_order(text,text,text,text,jsonb) to anon, authenticated;

-- Storage bucket for product images
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('product-images','product-images',true,5242880,array['image/jpeg','image/png','image/webp'])
on conflict (id) do nothing;

drop policy if exists "public read product images" on storage.objects;
create policy "public read product images" on storage.objects for select using (bucket_id='product-images');
drop policy if exists "admins upload product images" on storage.objects;
create policy "admins upload product images" on storage.objects for insert with check (bucket_id='product-images' and public.is_admin());
drop policy if exists "admins update product images" on storage.objects;
create policy "admins update product images" on storage.objects for update using (bucket_id='product-images' and public.is_admin()) with check (bucket_id='product-images' and public.is_admin());
drop policy if exists "admins delete product images" on storage.objects;
create policy "admins delete product images" on storage.objects for delete using (bucket_id='product-images' and public.is_admin());

